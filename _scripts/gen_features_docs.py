write("features/enterprise/webhook-trigger.mdx", f'''---
title: "Webhook 触发器"
description: "通过 Webhook 触发应用运行。"
---

## 功能概述

Webhook 触发器是八爪鱼RPA 提供的事件驱动集成方式。每个 RPA 应用可生成唯一的 Webhook 接口地址，外部业务系统通过 HTTP 请求调用该地址，即可触发对应应用在指定机器人上运行，并支持在请求中动态传入输入参数。

## 入口

在八爪鱼RPA 客户端左侧导航栏点击 **运行计划** → **触发器** → **新建触发器** → 选择 **Webhook 触发器**。

## 核心能力

- **事件触发**：电商订单生成、审批回调、消息推送等外部事件发生时自动启动 RPA 应用。
- **参数传递**：在 HTTP 请求中传入 JSON 参数，动态设置应用输入变量。
- **指定机器人**：可指定任务在哪个机器人上运行，便于负载管理。
- **签名校验**：支持 HmacSHA256 签名校验，保障调用安全。

## 请求格式

Webhook 接口接收 JSON 格式数据，示例结构如下：

```json
{{
  "timestamp": "当前时间的时间戳",
  "sign": "timestamp + \\n + 密钥的 HmacSHA256 签名，Base64 编码",
  "params": {{
    "变量1": "值1",
    "变量2": "值2"
  }},
  "SpecifiedBot": "机器人 ID"
}}
```

## 调用限制

当前 Webhook 接口的请求频率为：每秒最多 5 次，每分钟最多 20 次。

## 使用流程

1. 进入「触发器」模块，创建 Webhook 触发器。
2. 填写触发器名称，选择要运行的应用与机器人。
3. 复制生成的 Webhook 地址与签名密钥。
4. 在业务系统中配置 HTTP 回调，按格式发送请求。
5. 八爪鱼RPA 接收到请求后自动启动应用并传入参数。

<Info>
  使用 Webhook 触发器的前提是当前账号下拥有机器人。若按钮置灰，请检查账号套餐或机器人数量。
</Info>

{INFO_BLOCK}''')

